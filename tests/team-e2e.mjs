// Teams of two on separate phones see the same ladder; the other team is unaffected.
import { chromium } from "playwright";
const BASE = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined });
const phone = async () => await (await b.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: "reduce" })).newPage();
const fail = (m) => { console.log("FAIL", m); process.exit(1); };
const host = await phone();
await host.goto(BASE + "/room");
await host.getByRole("button", { name: "Open a room" }).click();
await host.locator(".room-code").waitFor();
const code = (await host.locator(".room-code").textContent()).replace(/\s/g, "");
const mates = [];
for (const n of ["Dayo", "Femi"]) {
  const p = await phone();
  await p.goto(`${BASE}/join/${code}`);
  await p.locator("#jname").fill(n);
  await p.getByRole("button", { name: "Join" }).click();
  mates.push(p);
}
await host.locator(".joined li").nth(1).waitFor();
await host.locator(".ticket", { hasText: "Word Ladder" }).click();
await host.getByText("2 teams").click();
await host.getByText("Take turns").click();
await host.screenshot({ path: "tests/screens/team-setup2.png", fullPage: true });
await host.getByRole("button", { name: /Start with/ }).click();
const all = [host, ...mates];
for (const p of all) await p.locator(".ladder-now").waitFor({ timeout: 10000 });
const info = [];
for (const p of all) info.push({ p, t: (await p.getByText(/You are in Team/).count()) ? await p.getByText(/You are in Team/).textContent() : "" });
const pair = info.filter((x) => x.t);
if (pair.length !== 2) fail(`expected 2 teammates, got ${pair.length}`);
console.log("ok teams:", pair.map((x) => x.t).join(" | "));
const solo = info.find((x) => !x.t).p;
// whoever's turn it is moves
const turnPhone = (await pair[0].p.locator(".turnbar.mine").count()) ? pair[0] : pair[1];
const other = turnPhone === pair[0] ? pair[1] : pair[0];
const before = (await turnPhone.p.locator(".ltile").allTextContents()).join("").toLowerCase();
await turnPhone.p.getByRole("button", { name: /Hint/ }).click();
await turnPhone.p.getByText(/Hint: try/).waitFor();
const hint = ((await turnPhone.p.getByText(/Hint: try/).textContent()).match(/“(\w+)”/) ?? [])[1].toLowerCase();
const diff = [...before].findIndex((c, i) => c !== hint[i]);
await turnPhone.p.locator(".ltile").nth(diff).click();
await turnPhone.p.locator(".lkey", { hasText: new RegExp(`^${hint[diff]}$`, "i") }).click();
await other.p.locator(".ladder li", { hasText: new RegExp(`^${before}$`, "i") }).waitFor({ timeout: 6000 });
await other.p.locator(".turnbar.mine").waitFor({ timeout: 6000 });
if ((await solo.locator(".ladder li").count()) !== 0) fail("other team's board changed");
console.log("ok teammates stay in sync, turn passed, other team untouched");
await turnPhone.p.screenshot({ path: "tests/screens/team-a.png", fullPage: true });
await other.p.screenshot({ path: "tests/screens/team-b.png", fullPage: true });
await b.close();
